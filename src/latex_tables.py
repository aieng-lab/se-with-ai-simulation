"""LaTeX exports of the §5 result tables.

The tables the paper typesets are generated from the analysis frames rather than
copied by hand, so a re-run of `scripts/analyze_results.py` cannot leave the paper
quoting stale numbers.  Each function returns a *snippet* meant to be ``\\input`` into
`paper/main.tex`, not a standalone document; the required packages are named in a
comment at the top of every file written.

`pandas.DataFrame.to_latex` is deliberately not used: on pandas 2.x it routes through
`Styler`, which needs jinja2 (not a dependency here), and it cannot emit the grouped
header these tables want.

Public API:
    index_optima_latex(optima, caption, label)      -> str
    save_latex_table(text, out_dir, name)           -> Path
"""

from __future__ import annotations

import math
import re
from pathlib import Path

import pandas as pd

from .config import AGENT_ROLE_ABBREV, AGENT_ROLE_COUNT, SCENARIO_GROUPS

#: Two-letter column heads for the eight agent roles, in k = 1..8 order.  The full
#: `AGENT_ROLE_ABBREV` labels ("Refactor", "Security") are far too wide for sixteen
#: adjacent numeric columns, so the caption carries the legend instead.
ROLE_HEADS: tuple[str, ...] = ("Ft", "De", "BF", "Rf", "Rv", "Se", "Te", "Do")

_TIER_INITIAL = {"low": "L", "medium": "M", "high": "H"}

_DEFAULT_CAPTION = (
    "Configuration with the lowest quality$\\times$cost index on each scenario's "
    "throughput-filtered Pareto front.  The scenario code gives the tier "
    "(L/M/H) of the "
    + ", ".join(SCENARIO_GROUPS)
    + " groups in that order.  Agent columns are the per-role counts of "
    "$A_\\mathrm{dev}$ and $A_\\mathrm{qa}$: "
    + ", ".join(f"{head} = {name}" for head, name in zip(ROLE_HEADS, AGENT_ROLE_ABBREV))
    + "."
)

_ESCAPES = {
    "\\": r"\textbackslash{}",
    "&": r"\&", "%": r"\%", "$": r"\$", "#": r"\#", "_": r"\_",
    "{": r"\{", "}": r"\}", "~": r"\textasciitilde{}", "^": r"\textasciicircum{}",
}
_ESCAPE_RE = re.compile("|".join(re.escape(c) for c in _ESCAPES))


def escape(text: object) -> str:
    """LaTeX-escape a cell's text.

    One pass over the input, not a chain of `str.replace` calls: the replacements
    themselves contain braces and backslashes, so a chain would escape its own
    output.
    """
    return _ESCAPE_RE.sub(lambda m: _ESCAPES[m.group()], str(text))


def scenario_code(row: "pd.Series") -> str:
    """The five tier initials of a row, in `SCENARIO_GROUPS` order, e.g. ``HLMHL``."""
    return "".join(
        _TIER_INITIAL.get(str(row.get(f"tier_{group}", "")), "?")
        for group in SCENARIO_GROUPS
    )


def format_number(x: object) -> str:
    """Three significant digits, switching to $m\\cdot10^{e}$ outside [0.01, 1e5).

    The §5 objectives span 31.6 to 3.3e7 across the scenarios, so a single fixed
    format is either unreadable at the top or lossy at the bottom.
    """
    try:
        value = float(x)
    except (TypeError, ValueError):
        return escape(x)
    if not math.isfinite(value):
        return "--"
    magnitude = abs(value)
    if magnitude == 0.0:
        return "0"
    if magnitude >= 1e5 or magnitude < 1e-2:
        mantissa, exponent = f"{value:.2e}".split("e")
        return f"${mantissa}{{\\cdot}}10^{{{int(exponent)}}}$"
    if magnitude >= 100:
        return f"{value:,.0f}"
    if magnitude >= 10:
        return f"{value:.1f}"
    return f"{value:.2f}"


def _int(x: object) -> str:
    return f"{int(round(float(x)))}"


def _fte(x: object) -> str:
    """Staffing level in FTE: whole levels stay integral, fractional ones keep 2 dp."""
    return f"{float(x):g}"


def index_optima_latex(
    optima: pd.DataFrame,
    caption: str = _DEFAULT_CAPTION,
    label: str = "tab:results:index_optima",
) -> str:
    """The per-scenario index optimum as a `longtable` snippet.

    `optima` is the frame of :func:`src.results_analysis.index_optimum`, normally
    grouped by scenario so it holds one row per scenario.  Columns follow the order
    the paper uses: scenario, objectives, the control variables, then the dev and QA
    agent counts — 25 columns in total.

    The search `strategy` that produced each row is *not* a column; it stays in the
    CSV that accompanies this file.
    """
    heads = (
        ["Scenario"]
        + ["Feat.", "Qual.", "Cost", "Index"]
        + ["$N$", "$M$", "$R$", "$F$"]
        + list(ROLE_HEADS) * 2
    )
    n_cols = len(heads)
    column_format = "l" + "r" * (n_cols - 1)

    group_row = " & ".join([
        "",
        r"\multicolumn{4}{c}{Objectives}",
        r"\multicolumn{4}{c}{Team}",
        r"\multicolumn{8}{c}{Development agents}",
        r"\multicolumn{8}{c}{QA agents}",
    ]) + r" \\"
    cmidrules = (
        r"\cmidrule(lr){2-5}\cmidrule(lr){6-9}"
        r"\cmidrule(lr){10-17}\cmidrule(lr){18-25}"
    )
    head_row = " & ".join(heads) + r" \\"

    header = [r"\toprule", group_row, cmidrules, head_row, r"\midrule"]

    lines = [
        "% Generated by scripts/analyze_results.py -- do not edit by hand.",
        "% Requires: \\usepackage{longtable} and \\usepackage{booktabs}.",
        f"% {n_cols} columns at \\tiny with \\tabcolsep=1.5pt fits the 338pt text block",
        "% of svjour3[smallextended] with no overfull box; widen either setting only",
        "% on a wider text block.",
        # The padding dominates the width: 25 columns carry 50*\tabcolsep, i.e. 300pt
        # at the 6pt default — nearly the whole text block before a single digit is
        # set.  Font size alone cannot recover that.
        r"\begingroup\tiny\setlength{\tabcolsep}{1.5pt}",
        f"\\begin{{longtable}}{{{column_format}}}",
        f"\\caption{{{caption}}}\\label{{{label}}}\\\\",
        *header,
        r"\endfirsthead",
        f"\\caption[]{{\\emph{{(continued)}}}}\\\\",
        *header,
        r"\endhead",
        r"\midrule",
        f"\\multicolumn{{{n_cols}}}{{r}}{{\\emph{{continued on next page}}}} \\\\",
        r"\endfoot",
        r"\bottomrule",
        r"\endlastfoot",
    ]

    for _, row in optima.iterrows():
        cells = (
            [escape(scenario_code(row))]
            + [format_number(row[c]) for c in
               ("value_mean", "quality_mean", "cost_mean", "quality_cost_index")]
            + [_fte(row["N"])]
            + [_int(row[c]) for c in ("M", "R", "F_freeze")]
            + [_int(row[f"a_dev_{k + 1}"]) for k in range(AGENT_ROLE_COUNT)]
            + [_int(row[f"a_qa_{k + 1}"]) for k in range(AGENT_ROLE_COUNT)]
        )
        lines.append(" & ".join(cells) + r" \\")

    lines += [r"\end{longtable}", r"\endgroup"]
    return "\n".join(lines) + "\n"


def save_latex_table(text: str, out_dir: Path, name: str) -> Path:
    """Write `text` to ``<out_dir>/<name>.tex``, report the path, and return it."""
    out_dir.mkdir(parents=True, exist_ok=True)
    dest = out_dir / f"{name}.tex"
    dest.write_text(text, encoding="utf-8")
    print(f"  Saved: {dest}")
    return dest

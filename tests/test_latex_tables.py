"""Tests for the LaTeX exports of `src.latex_tables`.

These check the structural contract a `\\input`-able snippet has to satisfy — a
balanced environment, one body row per input row, and a column count that agrees
between the format string, the header and every row.  A mismatch there is the one
failure mode that stops the paper from compiling, and it is invisible in the CSV.
"""

from __future__ import annotations

import itertools

import pandas as pd
import pytest

from src.config import AGENT_ROLE_COUNT, SCENARIO_GROUPS, SCENARIO_TIERS
from src.latex_tables import (
    escape,
    format_number,
    index_optima_latex,
    save_latex_table,
    scenario_code,
)

N_COLUMNS = 1 + 4 + 3 + 2 * AGENT_ROLE_COUNT


def _optimum_row(tiers: dict[str, str], i: int) -> dict:
    row = {f"tier_{group}": tiers[group] for group in SCENARIO_GROUPS}
    row.update(
        scenario_id="_".join(f"{g[0]}-{tiers[g][0]}" for g in SCENARIO_GROUPS),
        strategy="evolutionary",
        value_mean=12.0,
        quality_mean=1.5 + i,
        cost_mean=250.0 + i,
        quality_cost_index=(1.5 + i) * (250.0 + i),
        N=2, R=4, F_freeze=1,
    )
    for k in range(1, AGENT_ROLE_COUNT + 1):
        row[f"a_dev_{k}"] = k
        row[f"a_qa_{k}"] = 0 if k <= 2 else k
    return row


@pytest.fixture
def optima() -> pd.DataFrame:
    """One row for each of nine tier combinations, the rest of the groups medium."""
    rows = []
    for i, (human, project) in enumerate(
        itertools.product(SCENARIO_TIERS, SCENARIO_TIERS)
    ):
        tiers = {group: "medium" for group in SCENARIO_GROUPS}
        tiers.update(human=human, project=project)
        rows.append(_optimum_row(tiers, i))
    return pd.DataFrame(rows)


def _body_rows(text: str) -> list[str]:
    """The data rows: everything after \\endlastfoot, before \\end{longtable}."""
    body = text.split(r"\endlastfoot", 1)[1].split(r"\end{longtable}", 1)[0]
    return [line for line in body.splitlines() if line.strip()]


def test_environment_is_balanced_and_labelled(optima):
    text = index_optima_latex(optima)
    assert text.count(r"\begin{longtable}") == 1
    assert text.count(r"\end{longtable}") == 1
    assert text.count(r"\begingroup") == text.count(r"\endgroup") == 1
    assert r"\label{tab:results:index_optima}" in text
    assert r"\caption{" in text
    # The header is repeated for continuation pages.
    assert r"\endfirsthead" in text and r"\endhead" in text


def test_one_body_row_per_input_row(optima):
    rows = _body_rows(index_optima_latex(optima))
    assert len(rows) == len(optima)
    assert all(row.rstrip().endswith(r"\\") for row in rows)


def test_column_counts_agree(optima):
    text = index_optima_latex(optima)
    column_format = text.split(r"\begin{longtable}{", 1)[1].split("}", 1)[0]
    assert len(column_format) == N_COLUMNS

    header = next(line for line in text.splitlines() if line.startswith("Scenario &"))
    assert header.count("&") == N_COLUMNS - 1
    for row in _body_rows(text):
        assert row.count("&") == N_COLUMNS - 1


def test_scenario_code_uses_group_order(optima):
    tiers = {group: "medium" for group in SCENARIO_GROUPS}
    tiers.update(human="low", bugimpact="high")
    row = pd.Series({f"tier_{g}": t for g, t in tiers.items()})
    assert scenario_code(row) == "LMMMH"


def test_cells_are_escaped():
    assert escape("a_b") == r"a\_b"
    assert escape("100%") == r"100\%"
    assert escape("x&y") == r"x\&y"
    # Backslash is replaced first, so its replacement is not re-escaped.
    assert escape("\\") == r"\textbackslash{}"


@pytest.mark.parametrize(("value", "expected"), [
    (0.0, "0"),
    (1.234, "1.23"),
    (12.34, "12.3"),
    (1234.5, "1,234"),
    (float("nan"), "--"),
])
def test_format_number_bands(value, expected):
    assert format_number(value) == expected


def test_format_number_switches_to_scientific():
    assert format_number(3.32e7) == r"$3.32{\cdot}10^{7}$"
    assert format_number(0.001) == r"$1.00{\cdot}10^{-3}$"


def test_save_latex_table_writes_file(optima, tmp_path):
    path = save_latex_table(index_optima_latex(optima), tmp_path / "tables", "index_optima")
    assert path == tmp_path / "tables" / "index_optima.tex"
    assert path.read_text(encoding="utf-8").startswith("% Generated by")
